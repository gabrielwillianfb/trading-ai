"""SQLAlchemy 2.0 ORM models for the 11 core tables of the trading system.

Covers:
- market_candles
- features
- model_versions
- predictions
- signals
- orders
- fills
- positions
- portfolio_snapshots
- risk_events
- trades
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from sqlalchemy import (
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    JSON,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.data.storage.db import Base


def utc_now() -> datetime:
    """Return timezone-aware UTC current time."""
    return datetime.now(timezone.utc)


class MarketCandle(Base):
    """Stores historical and live OHLCV candlestick data."""

    __tablename__ = "market_candles"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    symbol: Mapped[str] = mapped_column(String(30), nullable=False, index=True)
    timeframe: Mapped[str] = mapped_column(String(10), nullable=False, index=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)

    open: Mapped[float] = mapped_column(Float, nullable=False)
    high: Mapped[float] = mapped_column(Float, nullable=False)
    low: Mapped[float] = mapped_column(Float, nullable=False)
    close: Mapped[float] = mapped_column(Float, nullable=False)
    volume: Mapped[float] = mapped_column(Float, nullable=False)

    quote_volume: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    trades_count: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    is_closed: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    __table_args__ = (
        UniqueConstraint("symbol", "timeframe", "timestamp", name="uq_candle_symbol_tf_time"),
        Index("idx_candle_lookup", "symbol", "timeframe", "timestamp"),
    )


class MarketFeature(Base):
    """Stores computed quantitative technical features tied to specific timestamps."""

    __tablename__ = "features"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    symbol: Mapped[str] = mapped_column(String(30), nullable=False, index=True)
    timeframe: Mapped[str] = mapped_column(String(10), nullable=False, index=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)

    candle_id: Mapped[Optional[int]] = mapped_column(
        Integer, ForeignKey("market_candles.id", ondelete="SET NULL"), nullable=True
    )
    values: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    __table_args__ = (
        UniqueConstraint("symbol", "timeframe", "timestamp", name="uq_feature_symbol_tf_time"),
        Index("idx_features_lookup", "symbol", "timeframe", "timestamp"),
    )


class ModelVersion(Base):
    """Tracks machine learning model versions, training metadata, and performance."""

    __tablename__ = "model_versions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    version: Mapped[str] = mapped_column(String(50), unique=True, nullable=False, index=True)
    model_type: Mapped[str] = mapped_column(String(50), default="xgboost_classifier", nullable=False)

    trained_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    training_start_date: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    training_end_date: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    feature_names: Mapped[List[str]] = mapped_column(JSON, nullable=False)
    hyperparameters: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    validation_metrics: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    test_metrics: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)

    dataset_hash: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    file_path: Mapped[str] = mapped_column(String(255), nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    predictions: Mapped[List["Prediction"]] = relationship(
        "Prediction", back_populates="model_version", cascade="all, delete-orphan", lazy="selectin"
    )


class Prediction(Base):
    """Stores probabilities and inferences generated by ML models."""

    __tablename__ = "predictions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    symbol: Mapped[str] = mapped_column(String(30), nullable=False, index=True)
    timeframe: Mapped[str] = mapped_column(String(10), nullable=False)

    model_version_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("model_versions.id", ondelete="CASCADE"), nullable=False, index=True
    )
    probability_up: Mapped[float] = mapped_column(Float, nullable=False)
    probability_down: Mapped[float] = mapped_column(Float, nullable=False)
    predicted_class: Mapped[int] = mapped_column(Integer, nullable=False)
    horizon: Mapped[int] = mapped_column(Integer, default=12, nullable=False)

    raw_features: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    model_version: Mapped["ModelVersion"] = relationship(
        "ModelVersion", back_populates="predictions", lazy="selectin"
    )
    signals: Mapped[List["Signal"]] = relationship(
        "Signal", back_populates="prediction", lazy="selectin"
    )

    __table_args__ = (
        Index("idx_prediction_symbol_time", "symbol", "timestamp"),
    )


class Signal(Base):
    """Stores BUY/SELL/HOLD decision signals with confidence levels."""

    __tablename__ = "signals"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    symbol: Mapped[str] = mapped_column(String(30), nullable=False, index=True)
    timeframe: Mapped[str] = mapped_column(String(10), nullable=False)

    signal_type: Mapped[str] = mapped_column(String(10), nullable=False)  # BUY, SELL, HOLD
    probability_up: Mapped[float] = mapped_column(Float, nullable=False)
    probability_down: Mapped[float] = mapped_column(Float, nullable=False)
    confidence: Mapped[float] = mapped_column(Float, nullable=False)
    threshold_used: Mapped[float] = mapped_column(Float, nullable=False)

    prediction_id: Mapped[Optional[int]] = mapped_column(
        Integer, ForeignKey("predictions.id", ondelete="SET NULL"), nullable=True
    )
    is_processed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    prediction: Mapped[Optional["Prediction"]] = relationship(
        "Prediction", back_populates="signals", lazy="selectin"
    )
    orders: Mapped[List["Order"]] = relationship(
        "Order", back_populates="signal", lazy="selectin"
    )


class Order(Base):
    """Tracks order lifecycle after Risk Manager approval."""

    __tablename__ = "orders"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    client_order_id: Mapped[str] = mapped_column(String(64), unique=True, nullable=False, index=True)
    exchange_order_id: Mapped[Optional[str]] = mapped_column(String(64), nullable=True, index=True)

    symbol: Mapped[str] = mapped_column(String(30), nullable=False, index=True)
    side: Mapped[str] = mapped_column(String(10), nullable=False)  # BUY, SELL
    order_type: Mapped[str] = mapped_column(String(20), default="MARKET", nullable=False)
    quantity: Mapped[float] = mapped_column(Float, nullable=False)
    price: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    stop_loss: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    take_profit: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    status: Mapped[str] = mapped_column(
        String(20), default="PENDING", nullable=False
    )  # PENDING, APPROVED, REJECTED, FILLED, CANCELLED, EXPIRED
    mode: Mapped[str] = mapped_column(String(20), default="paper", nullable=False)  # paper, testnet
    rejection_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    signal_id: Mapped[Optional[int]] = mapped_column(
        Integer, ForeignKey("signals.id", ondelete="SET NULL"), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, onupdate=utc_now, nullable=False)

    signal: Mapped[Optional["Signal"]] = relationship(
        "Signal", back_populates="orders", lazy="selectin"
    )
    fills: Mapped[List["Fill"]] = relationship(
        "Fill", back_populates="order", cascade="all, delete-orphan", lazy="selectin"
    )


class Fill(Base):
    """Execution fills for orders including fees and slippage."""

    __tablename__ = "fills"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    order_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("orders.id", ondelete="CASCADE"), nullable=False, index=True
    )
    client_order_id: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    symbol: Mapped[str] = mapped_column(String(30), nullable=False)
    side: Mapped[str] = mapped_column(String(10), nullable=False)

    price: Mapped[float] = mapped_column(Float, nullable=False)
    quantity: Mapped[float] = mapped_column(Float, nullable=False)
    fee: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    fee_asset: Mapped[str] = mapped_column(String(20), default="USDT", nullable=False)
    slippage_pct: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)

    timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    order: Mapped["Order"] = relationship(
        "Order", back_populates="fills", lazy="selectin"
    )


class Position(Base):
    """Tracks active and closed trading positions."""

    __tablename__ = "positions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
